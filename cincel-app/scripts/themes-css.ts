/**
 * `npm run themes:css` (redesign BE §5.3, §15): regenerates the token block of
 * `app/globals.css` from `THEME_PRESETS.azul`. Not run until Phase 9 (Cleanup);
 * until then `globals.css` keeps today's values (drift test:
 * `tests/unit/themes-css-snapshot.test.ts`).
 *
 * The token block is everything from the first `:root {` rule up to
 * `@layer base`: the light `:root`, the explicit dark rule
 * (`.dark, :root[data-theme="dark"]`) and the OS-dark mirror inside
 * `@media (prefers-color-scheme: dark)`. Everything else in the file is kept.
 *
 * Usage:
 *   npm run themes:css              writes app/globals.css
 *   npm run themes:css -- --stdout  prints the generated block only
 *   npm run themes:css -- --check   exits 1 when app/globals.css differs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import type { OrgAppearance } from "../lib/types/redesign";
import { THEME_PRESETS, TOKEN_NAMES } from "../lib/ui/themes";

const BLOCK_START = /^:root \{$/m;
const BLOCK_END = /^@layer base \{$/m;

function declarations(appearance: OrgAppearance, mode: "light" | "dark", indent: string): string {
  const lines = TOKEN_NAMES.map((name) => `${indent}--${name}: ${appearance.tokens[name][mode]};`);
  if (mode === "light") lines.push(`${indent}--radius: ${appearance.shape.radius / 16}rem;`);
  return lines.join("\n");
}

/** The generated token block (ends with a blank line, ready to precede `@layer base`). */
export function themesCss(appearance: OrgAppearance = THEME_PRESETS.azul): string {
  return [
    `/* Generated by \`npm run themes:css\` from THEME_PRESETS.${appearance.baseTheme} (lib/ui/themes.ts). Do not edit by hand. */`,
    ":root {",
    declarations(appearance, "light", "  "),
    "}",
    "",
    "/* Dark tokens: explicit choice (.dark / data-theme) and the OS default, kept identical. */",
    ".dark,",
    ':root[data-theme="dark"] {',
    declarations(appearance, "dark", "  "),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    declarations(appearance, "dark", "    "),
    "  }",
    "}",
    "",
    "",
  ].join("\n");
}

/** The token block of a `globals.css` source (from `:root {` up to `@layer base {`). */
export function extractTokenBlock(css: string): string {
  const start = BLOCK_START.exec(css);
  const end = BLOCK_END.exec(css);
  if (!start || !end || end.index <= start.index) {
    throw new Error("globals.css: token block not found (expected `:root {` before `@layer base {`)");
  }
  return css.slice(start.index, end.index);
}

/** `css` with its token block replaced by `block`; the rest of the file is untouched. */
export function replaceTokenBlock(css: string, block: string): string {
  const current = extractTokenBlock(css);
  const at = css.indexOf(current);
  // A previous run's header comment sits right before `:root {`; drop it so it is not duplicated.
  const before = css.slice(0, at).replace(/\/\* Generated by `npm run themes:css`[^\n]*\*\/\n$/, "");
  return before + block + css.slice(at + current.length);
}

/** Resolved from the app root (`npm run` always runs there). */
export const GLOBALS_CSS_PATH = resolve(process.cwd(), "app", "globals.css");

function main(argv: readonly string[]): number {
  const block = themesCss();
  if (argv.includes("--stdout")) {
    process.stdout.write(block);
    return 0;
  }
  const css = readFileSync(GLOBALS_CSS_PATH, "utf8");
  const next = replaceTokenBlock(css, block);
  if (argv.includes("--check")) {
    if (next !== css) {
      console.error("app/globals.css differs from THEME_PRESETS.azul; run `npm run themes:css`.");
      return 1;
    }
    console.log("app/globals.css matches THEME_PRESETS.azul.");
    return 0;
  }
  writeFileSync(GLOBALS_CSS_PATH, next);
  console.log("app/globals.css regenerated from THEME_PRESETS.azul.");
  return 0;
}

if (process.argv[1]?.endsWith("themes-css.ts")) {
  process.exitCode = main(process.argv.slice(2));
}
