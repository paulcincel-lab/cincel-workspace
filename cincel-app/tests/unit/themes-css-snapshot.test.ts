/**
 * Drift guard for `app/globals.css` (redesign BE §5.3, §15; review B17): until
 * Phase 9 its token block stays exactly today's grayscale values, so legacy
 * pages render unchanged with `ui.redesign` off. `npm run themes:css`
 * regenerates it from `THEME_PRESETS.azul` only in Phase 9, when this test is
 * updated to assert the generated block instead.
 */
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import { describe, expect, it } from "vitest";

import { extractTokenBlock, replaceTokenBlock, themesCss } from "@/scripts/themes-css";
import { THEME_PRESETS, TOKEN_NAMES } from "@/lib/ui/themes";

const APP_ROOT = resolve(__dirname, "..", "..");
const globalsCss = readFileSync(resolve(APP_ROOT, "app", "globals.css"), "utf8");

/** sha256 of today's token block (`:root {` … up to `@layer base {`). */
const TOKEN_BLOCK_SHA256 = "70eb016b4db2cc5796343e45193ccda9eb24687d602cb4093f993e31a42497ee";

function varsOf(rule: string): Record<string, string> {
  return Object.fromEntries([...rule.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}

function ruleBody(css: string, selector: string): string {
  const at = css.indexOf(selector);
  expect(at, selector).toBeGreaterThanOrEqual(0);
  const open = css.indexOf("{", at);
  return css.slice(open + 1, css.indexOf("}", open));
}

describe("app/globals.css drift (unchanged until Phase 9)", () => {
  const block = extractTokenBlock(globalsCss);

  it("the token block is byte-for-byte today's", () => {
    expect(createHash("sha256").update(block).digest("hex")).toBe(TOKEN_BLOCK_SHA256);
  });

  it("still carries today's grayscale light values, not a preset", () => {
    const light = varsOf(ruleBody(block, ":root {"));
    expect(light).toMatchObject({
      background: "#f5f5f4",
      foreground: "#0a0a0a",
      primary: "#0a0a0a",
      "muted-foreground": "#6b6b6b",
      "chart-3": "#1baf7a",
      "chart-4": "#eda100",
      sidebar: "#0a0a0a",
      radius: "0.625rem",
    });
    expect(light.background).not.toBe(THEME_PRESETS.azul.tokens.background.light);
  });

  it("keeps the explicit dark rule and the OS-dark mirror identical", () => {
    const explicit = varsOf(ruleBody(block, ':root[data-theme="dark"] {'));
    const media = varsOf(ruleBody(block, ':root:not([data-theme="light"]) {'));
    expect(media).toEqual(explicit);
    expect(explicit.destructive).toBe("#e0574a");
  });

  it("has not been regenerated yet (npm run themes:css is Phase 9)", () => {
    expect(globalsCss).not.toContain("Generated by `npm run themes:css`");
    expect(replaceTokenBlock(globalsCss, themesCss())).not.toBe(globalsCss);
  });
});

describe("themesCss()", () => {
  const generated = themesCss();

  it("emits every Azul token for light, explicit dark and OS dark", () => {
    const light = varsOf(ruleBody(generated, ":root {"));
    const dark = varsOf(ruleBody(generated, ':root[data-theme="dark"] {'));
    const media = varsOf(ruleBody(generated, ':root:not([data-theme="light"]) {'));
    for (const name of TOKEN_NAMES) {
      expect(light[name], name).toBe(THEME_PRESETS.azul.tokens[name].light);
      expect(dark[name], name).toBe(THEME_PRESETS.azul.tokens[name].dark);
    }
    expect(media).toEqual(dark);
    expect(light.radius).toBe(`${THEME_PRESETS.azul.shape.radius / 16}rem`);
  });

  it("generates from another preset when asked", () => {
    expect(varsOf(ruleBody(themesCss(THEME_PRESETS.calido), ":root {")).background).toBe("#f7f5f2");
  });

  it("replaces only the token block, idempotently", () => {
    const once = replaceTokenBlock(globalsCss, generated);
    expect(replaceTokenBlock(once, generated)).toBe(once);
    expect(once.startsWith(globalsCss.slice(0, globalsCss.indexOf(":root {")))).toBe(true);
    expect(once.endsWith(globalsCss.slice(globalsCss.indexOf("@layer base {")))).toBe(true);
    expect(extractTokenBlock(once)).toBe(generated.slice(generated.indexOf(":root {")));
  });

  it("is wired as npm run themes:css", () => {
    const pkg = JSON.parse(readFileSync(resolve(APP_ROOT, "package.json"), "utf8")) as { scripts: Record<string, string> };
    expect(pkg.scripts["themes:css"]).toBe("tsx scripts/themes-css.ts");
  });
});
